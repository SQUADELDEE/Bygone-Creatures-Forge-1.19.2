    // ---- Nest territory ----
    // A wild bird generated by TerrorBirdNestFeature belongs to a nest: it wanders only within NEST_ROAM_RADIUS of
    // it, and attacks anything that strays within GUARD_RADIUS. Not saved as a restriction (vanilla doesn't),
    // so it's re-applied on load. Taming frees the bird of it; so does losing every egg.
    private static final int NEST_ROAM_RADIUS = 18;
    private static final double GUARD_RADIUS = 7.0D;
    private static final double NEST_LEASH_SQR = 26.0D * 26.0D;
    @Nullable
    private BlockPos nestPos;

    public TerrorBirdEntity(EntityType<? extends TamableAnimal> entityType, Level level) {
        super(entityType, level);
    }

    public void setNestPos(@Nullable BlockPos pos) {
        this.nestPos = pos;
        if (pos != null && !isTame()) restrictTo(pos, NEST_ROAM_RADIUS);
        else clearRestriction();
    }

    @Nullable
    public BlockPos getNestPos() {
        return nestPos;
    }

    private boolean isNestIntruder(LivingEntity e) {
        if (nestPos == null || isTame() || isBaby() || e == this || !e.isAlive()) return false;
        if (e instanceof TerrorBirdEntity || e instanceof ArmorStand) return false;
        return e.blockPosition().closerThan(nestPos, GUARD_RADIUS);
    }

    private boolean nestHasEggs() {
        for (BlockPos pos : BlockPos.betweenClosed(nestPos.offset(-5, -1, -5), nestPos.offset(5, 3, 5))) {
            if (level().getBlockState(pos).is(ModBlocks.TERRORBIRDEGG.get())) return true;
        }
        return false;
    }

    // Called when an egg is broken: every wild bird that nests there turns on whoever did it.
    public static void defendNest(Level level, BlockPos eggPos, LivingEntity culprit) {
        AABB area = new AABB(eggPos).inflate(24.0D);
        for (TerrorBirdEntity bird : level.getEntitiesOfClass(TerrorBirdEntity.class, area,
                b -> !b.isTame() && b.nestPos != null && b.nestPos.closerThan(eggPos, 12.0D))) {
            if (bird.canAttack(culprit)) {
                bird.setLastHurtByMob(culprit);
                bird.setTarget(culprit);
            }
        }
    }

    // Wanders back to the nest if shoved or lured far from it.
    private class ReturnToNestGoal extends Goal {
        ReturnToNestGoal() {
            this.setFlags(EnumSet.of(Goal.Flag.MOVE));
        }

        @Override
        public boolean canUse() {
            return nestPos != null && !isTame() && getTarget() == null && !isPassenger()
                    && distanceToSqr(Vec3.atBottomCenterOf(nestPos)) > NEST_LEASH_SQR;
        }

        @Override
        public boolean canContinueToUse() {
            return nestPos != null && !getNavigation().isDone() && getTarget() == null
                    && distanceToSqr(Vec3.atBottomCenterOf(nestPos)) > 64.0D;
        }

        @Override
        public void start() {
            getNavigation().moveTo(nestPos.getX() + 0.5D, nestPos.getY(), nestPos.getZ() + 0.5D, 1.0D);
        }
    }

