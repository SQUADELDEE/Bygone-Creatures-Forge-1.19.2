    private boolean isNestIntruder(LivingEntity e) {
        if (nestPos == null || isTame() || isBaby() || e == this || !e.isAlive()) return false;
        if (e instanceof TerrorBirdEntity || e instanceof ArmorStand) return false;
        return e.blockPosition().closerThan(nestPos, GUARD_RADIUS);
    }

    private boolean nestHasEggs() {
        for (BlockPos pos : BlockPos.betweenClosed(nestPos.offset(-5, -1, -5), nestPos.offset(5, 3, 5))) {
            if (level().getBlockState(pos).is(ModBlocks.TERRORBIRDEGG.get())) return true;
        }
        return false;
    }

    // Called when an egg is broken: every wild bird that nests there turns on whoever did it.
    public static void defendNest(Level level, BlockPos eggPos, LivingEntity culprit) {
        AABB area = new AABB(eggPos).inflate(24.0D);
        for (TerrorBirdEntity bird : level.getEntitiesOfClass(TerrorBirdEntity.class, area,
                b -> !b.isTame() && b.nestPos != null && b.nestPos.closerThan(eggPos, 12.0D))) {
            if (bird.canAttack(culprit)) {
                bird.setLastHurtByMob(culprit);
                bird.setTarget(culprit);
            }
        }
    }

